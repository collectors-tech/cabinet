import { z } from 'zod'

// We're keeping a simple non-relational schema here.
// IRL, you will have a schema for your data models.
export const taskSchema = z.object({
  id: z.string(),
  itemID: z.string().optional(),
  wishlistEntryID: z.string().optional(),
  title: z.string(),
  thumbnailUrl: z.string().optional(),
  partNumber: z.string().optional(),
  itemType: z.string().optional(),
  packagingGradeType: z.string().optional(),
  condition: z.string().optional(),
  status: z.string(),
  label: z.string(),
  collectionName: z.string().optional(),
  priority: z.string(),
  notes: z.string().optional(),
  belowTargetNow: z.boolean().optional(),
  targetPrice: z.number().optional(),
  marketPrice: z.number().optional(),
  priceTrend: z.enum(['up', 'steady', 'down', 'unknown']).optional(),
  priceHistory: z.array(z.number()).optional(),
  priceHistoryDates: z.array(z.string()).optional(),
  priceSampleCount: z.number().optional(),
  priceFirstDate: z.string().optional(),
  priceLatestDate: z.string().optional(),
  wishlistCreatedAt: z.string().optional(),
  wishlistPriceUpdatedAt: z.string().optional(),
  priceSources: z.array(z.string()).optional(),
  priceStockCount: z.number().optional(),
  highlightHit: z.boolean().optional(),
  owned: z.boolean().optional(),
  delivered: z.boolean().optional(),
  pricePaid: z.number().optional(),
  purchaseUrl: z.string().optional(),
  purchaseDate: z.string().optional(),
  purchaseCondition: z.string().optional(),
  quantity: z.number().optional(),
  neededQuantity: z.number().optional(),
  deleted: z.boolean().optional(),
})

export type Task = z.infer<typeof taskSchema>
